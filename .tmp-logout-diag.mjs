const BASE = "http://127.0.0.1:5173";
const targets = await (await fetch("http://127.0.0.1:9222/json/list")).json();
const target = targets.find((t) => t.type === "page" && t.url.includes("5173"));
const ws = new WebSocket(target.webSocketDebuggerUrl);
let id = 0; const pending = new Map();
ws.addEventListener("message", (e) => { const m = JSON.parse(e.data); if (m.id && pending.has(m.id)) { pending.get(m.id)(m); pending.delete(m.id); } });
await new Promise((r) => ws.addEventListener("open", r));
const send = (method, params = {}) => { const i = ++id; ws.send(JSON.stringify({ id: i, method, params })); return new Promise((res, rej) => pending.set(i, (m) => m.error ? rej(new Error(JSON.stringify(m.error))) : res(m.result))); };
const ev = async (expr) => { const r = await send("Runtime.evaluate", { expression: expr, returnByValue: true, awaitPromise: true }); if (r.exceptionDetails) return "ERR " + JSON.stringify(r.exceptionDetails.exception?.description); return r.result.value; };
const sleep = (ms) => new Promise((r) => setTimeout(r, ms));
await send("Network.setCookie", { name: "role", value: "operator", domain: "127.0.0.1", path: "/" });
await send("Page.navigate", { url: BASE + "/dashboard" });
await sleep(2500);
console.log("before:", await ev(`JSON.stringify({ path: location.pathname, cookie: document.cookie })`));
await ev(`[...document.querySelectorAll('header button')].find((b) => b.textContent.trim() === 'Logout')?.click()`);
await sleep(600);
console.log("dialog buttons:", await ev(`JSON.stringify([...document.querySelectorAll('[data-slot="alert-dialog-content"] button')].map((b) => ({ text: b.textContent, slot: b.getAttribute('data-slot') })))`));
await ev(`[...document.querySelectorAll('[data-slot="alert-dialog-content"] button')].find((b) => b.textContent.trim() === 'Sign out')?.click()`);
await sleep(250);
console.log("after 250ms:", await ev(`JSON.stringify({ path: location.pathname, cookie: document.cookie })`));
await sleep(1500);
console.log("after 1.7s:", await ev(`JSON.stringify({ path: location.pathname, cookie: document.cookie, text: document.body.innerText.slice(0, 150) })`));
ws.close();
